"""Stable Polymarket identifiers shared by the offline adapters."""

from __future__ import annotations

from nautilus_trader.adapters.polymarket import POLYMARKET_VENUE
from nautilus_trader.model import InstrumentId, TradeId

_FNV_OFFSET_BASIS = 0xCBF29CE484222325
_FNV_PRIME = 0x100000001B3
_U64_MASK = (1 << 64) - 1


def get_polymarket_instrument_id(
    condition_id: str, token_id: str | int
) -> InstrumentId:
    """Return the canonical ``condition-token.POLYMARKET`` instrument ID."""
    return InstrumentId.from_str(f"{condition_id}-{token_id}.{POLYMARKET_VENUE}")


def get_polymarket_condition_id(instrument_id: InstrumentId) -> str:
    """Extract a condition ID from a canonical Polymarket instrument ID."""
    condition_id, _ = _split_symbol(instrument_id)
    return condition_id


def get_polymarket_token_id(instrument_id: InstrumentId) -> str:
    """Extract a token ID from a canonical Polymarket instrument ID."""
    _, token_id = _split_symbol(instrument_id)
    return token_id


def determine_trade_id(
    asset_id: str,
    *,
    is_buy: bool,
    price: str,
    size: str,
    timestamp: str,
) -> TradeId:
    """Match the deterministic market-data trade ID generated by the v2 Rust adapter."""
    fields = (asset_id, "B" if is_buy else "S", price, size, timestamp)
    value = _FNV_OFFSET_BASIS
    for byte in b"\x1f".join(field.encode() for field in fields):
        value ^= byte
        value = (value * _FNV_PRIME) & _U64_MASK
    return TradeId(f"{value:016x}")


def _split_symbol(instrument_id: InstrumentId) -> tuple[str, str]:
    parts = instrument_id.symbol.value.split("-")
    if len(parts) != 2 or not all(parts):
        raise ValueError(
            "Invalid Polymarket instrument ID format: expected "
            f"'{{condition_id}}-{{token_id}}', was '{instrument_id.symbol.value}'",
        )
    return parts[0], parts[1]
